/** The mark as a rounded tile (favicons, app icons) or filling the whole square (icons the platform masks itself). */
function markSvg({ bleed = false, inset = 1 } = {}) {
  const transform = inset === 1 ? "" : ` transform="translate(16 16) scale(${inset}) translate(-16 -16)"`;
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32"${bleed ? "" : ' rx="7"'} fill="${COBALT}"/>${corners(transform)}</svg>`;
}

