async function renderTemplate({ template, out, width, height, scale = 1, fill }) {
  const context = await browser.newContext({ viewport: { width, height }, deviceScaleFactor: scale });
  const page = await context.newPage();
  await page.goto(pathToFileURL(path.join(templates, template)).href);
  if (fill) {
    await page.evaluate((values) => {
      for (const [key, value] of Object.entries(values)) {
        for (const element of document.querySelectorAll(`[data-token="${key}"]`)) element.textContent = value;
      }
    }, fill);
  }
  // Fonts load lazily, so ask for each face by name: a template then renders the same whether or not the font was already in use.
  const fontsLoaded = await page.evaluate(async () => {
    const faces = ['400 20px "Archivo"', '500 20px "Archivo"', '600 20px "Archivo"'];
    const loaded = await Promise.all(faces.map((face) => document.fonts.load(face)));
    await document.fonts.ready;
    return loaded.every((result) => result.length > 0);
  });
  if (!fontsLoaded) throw new Error(`${template}: the brand fonts did not load. Run npm install first.`);
  await page.screenshot({ path: path.join(exportsDir, out), clip: { x: 0, y: 0, width, height } });
  await context.close();
  console.log(`  ${out}`);
}

async function renderIcon(svg, size) {
  const context = await browser.newContext({ viewport: { width: size, height: size } });
  const page = await context.newPage();
  await page.setContent(`<style>html,body{margin:0;background:transparent}svg{display:block;width:${size}px;height:${size}px}</style>${svg}`);
  const data = await page.screenshot({ omitBackground: true, clip: { x: 0, y: 0, width: size, height: size } });
  await context.close();
  return data;
}

async function writeIcon(svg, size, out) {
  await writeFile(path.join(exportsDir, out), await renderIcon(svg, size));
  console.log(`  ${out}`);
}

