async function buildWordmarks() {
  const woff = await readFile(path.join(root, "node_modules/@fontsource/archivo/files/archivo-latin-600-normal.woff"));
  const font = opentype.parse(woff.buffer.slice(woff.byteOffset, woff.byteOffset + woff.byteLength));
  const size = 23;
  const capHeight = (font.tables.os2.sCapHeight / font.unitsPerEm) * size;
  // Cap height centred on the 32-unit tile; the text starts one tile-third after it.
  const baseline = 16 + capHeight / 2;
  // Set glyph by glyph: opentype.js cannot run every substitution feature this font carries, and the name needs none of them.
  const text = new opentype.Path();
  const unit = size / font.unitsPerEm;
  const glyphs = [..."JustResize"].map((character) => font.charToGlyph(character));
  let x = 42;
  glyphs.forEach((glyph, index) => {
    text.extend(glyph.getPath(x, baseline, size));
    const kerning = index + 1 < glyphs.length ? font.getKerningValue(glyph, glyphs[index + 1]) : 0;
    x += (glyph.advanceWidth + kerning) * unit + size * -0.01;
  });
  const width = Math.ceil(text.getBoundingBox().x2 + 1);

  const wordmark = (fill, note) =>
    `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} 32" role="img" aria-label="JustResize">\n` +
    `  <!-- ${note} Generated by scripts/brand/export.mjs; the letters are outlines of Archivo SemiBold. -->\n` +
    `  <rect width="32" height="32" rx="7" fill="${COBALT}"/>\n  ${corners()}\n` +
    `  <path d="${text.toPathData(2)}" fill="${fill}"/>\n</svg>\n`;

  await writeFile(path.join(brand, "justresize-wordmark-dark.svg"), wordmark("#ececef", "For dark backgrounds."));
  await writeFile(path.join(brand, "justresize-wordmark-light.svg"), wordmark("#15161a", "For light backgrounds."));
}

/** PNG entries in an ICO container: every current browser reads them, and it keeps the favicon crisp at each size. */
function ico(images) {
  const header = Buffer.alloc(6 + images.length * 16);
  header.writeUInt16LE(1, 2);
  header.writeUInt16LE(images.length, 4);
  let offset = header.length;
  images.forEach(({ size, data }, index) => {
    const entry = 6 + index * 16;
    header.writeUInt8(size === 256 ? 0 : size, entry);
    header.writeUInt8(size === 256 ? 0 : size, entry + 1);
    header.writeUInt16LE(1, entry + 4);
    header.writeUInt16LE(32, entry + 6);
    header.writeUInt32LE(data.length, entry + 8);
    header.writeUInt32LE(offset, entry + 12);
    offset += data.length;
  });
  return Buffer.concat([header, ...images.map((image) => image.data)]);
}

