/**
 * Builds every brand asset from its source, the same way each time:
 *
 *   npm run brand:export
 *
 * - Wordmark SVGs are outlined from the real Archivo font, so they
 *   look right without the font installed.
 * - PNGs are rendered from the HTML templates in brand-assets/templates
 *   with headless Chromium at an exact size — never screenshotted by hand.
 * - The files the site itself uses are copied into app/ and public/brand/,
 *   including one share image per tool page (public/brand/og/<slug>.png).
 *
 * Token graphics follow lib/config/site.ts: none are made when the token is
 * disabled, and the one graphic that carries a mint address is only made
 * once the token is live with a real mint. No placeholder address is ever
 * rendered into an image.
 */
